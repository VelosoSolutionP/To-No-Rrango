using ToNoRango.Domain.Establishments;

namespace ToNoRango.Application.Establishments;

public sealed record EstablishmentDto(
    Guid Id,
    Guid TenantId,
    string Name,
    string Slug,
    string? Description,
    string? LogoUrl,
    string? CoverUrl,
    string? Phone,
    string? WhatsApp,
    string? AddressLine,
    string? City,
    string? State,
    string? PostalCode,
    string TimeZone,
    bool IsActive,
    bool IsPickupEnabled,
    bool IsDeliveryEnabled,
    bool IsDineInEnabled,
    long DeliveryFeeInCents,
    long MinimumOrderInCents,
    string PrimaryColor,
    string SecondaryColor)
{
    public static EstablishmentDto From(Establishment establishment) => new(
        establishment.Id,
        establishment.TenantId,
        establishment.Name,
        establishment.Slug,
        establishment.Description,
        establishment.LogoUrl,
        establishment.CoverUrl,
        establishment.Phone,
        establishment.WhatsApp,
        establishment.AddressLine,
        establishment.City,
        establishment.State,
        establishment.PostalCode,
        establishment.TimeZone,
        establishment.IsActive,
        establishment.IsPickupEnabled,
        establishment.IsDeliveryEnabled,
        establishment.IsDineInEnabled,
        establishment.DeliveryFeeInCents,
        establishment.MinimumOrderInCents,
        establishment.PrimaryColor,
        establishment.SecondaryColor);
}

